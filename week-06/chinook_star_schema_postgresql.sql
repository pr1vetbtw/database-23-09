-- Chinook Data Warehouse: Star Schema for PostgreSQL / pgAdmin 4
-- Grain: one row in fact_sales = one InvoiceLine (one track on one invoice).
-- Run this script while connected to the target PostgreSQL database (e.g. postgres).
-- It creates a schema named chinook_dw inside that database.

CREATE SCHEMA IF NOT EXISTS chinook_dw;
SET search_path TO chinook_dw, public;

-- Drop in dependency order so the script can be rerun.
DROP TABLE IF EXISTS fact_sales;
DROP TABLE IF EXISTS dim_billing_location;
DROP TABLE IF EXISTS dim_track;
DROP TABLE IF EXISTS dim_customer;
DROP TABLE IF EXISTS dim_date;

CREATE TABLE dim_date (
    date_key        INTEGER PRIMARY KEY, -- YYYYMMDD
    full_date       DATE NOT NULL UNIQUE,
    day_of_month    SMALLINT NOT NULL CHECK (day_of_month BETWEEN 1 AND 31),
    day_name        VARCHAR(10) NOT NULL,
    day_of_week     SMALLINT NOT NULL CHECK (day_of_week BETWEEN 1 AND 7), -- 1=Monday
    week_of_year    SMALLINT NOT NULL CHECK (week_of_year BETWEEN 1 AND 53),
    month_number    SMALLINT NOT NULL CHECK (month_number BETWEEN 1 AND 12),
    month_name      VARCHAR(10) NOT NULL,
    quarter_number  SMALLINT NOT NULL CHECK (quarter_number BETWEEN 1 AND 4),
    year_number     SMALLINT NOT NULL
);

CREATE INDEX ix_dim_date_year_month
    ON dim_date (year_number, month_number);

CREATE TABLE dim_customer (
    customer_key    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id     INTEGER NOT NULL UNIQUE, -- original Chinook Customer.CustomerId
    first_name      VARCHAR(40) NOT NULL,
    last_name       VARCHAR(20) NOT NULL,
    company         VARCHAR(80),
    address         VARCHAR(70),
    city            VARCHAR(40),
    state           VARCHAR(40),
    country         VARCHAR(40),
    postal_code     VARCHAR(10),
    phone           VARCHAR(24),
    fax             VARCHAR(24),
    email           VARCHAR(60)
);

CREATE INDEX ix_dim_customer_name
    ON dim_customer (last_name, first_name);
CREATE INDEX ix_dim_customer_country
    ON dim_customer (country);

CREATE TABLE dim_track (
    track_key       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    track_id        INTEGER NOT NULL UNIQUE, -- original Chinook Track.TrackId
    track_name      VARCHAR(200) NOT NULL,
    album_id        INTEGER,
    album_title     VARCHAR(160),
    artist_id       INTEGER,
    artist_name     VARCHAR(120),
    genre_id        INTEGER,
    genre_name      VARCHAR(120),
    media_type_id   INTEGER,
    media_type_name VARCHAR(120),
    composer        VARCHAR(220),
    milliseconds    INTEGER CHECK (milliseconds IS NULL OR milliseconds >= 0),
    bytes           BIGINT CHECK (bytes IS NULL OR bytes >= 0)
);

CREATE INDEX ix_dim_track_artist ON dim_track (artist_name);
CREATE INDEX ix_dim_track_genre ON dim_track (genre_name);
CREATE INDEX ix_dim_track_album ON dim_track (album_title);

CREATE TABLE dim_billing_location (
    billing_location_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    billing_address      VARCHAR(70),
    billing_city         VARCHAR(40),
    billing_state        VARCHAR(40),
    billing_country      VARCHAR(40),
    billing_postal_code  VARCHAR(10)
);

CREATE INDEX ix_dim_location_country_city
    ON dim_billing_location (billing_country, billing_city);

CREATE TABLE fact_sales (
    sales_key              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_line_id        INTEGER NOT NULL UNIQUE, -- source transaction row
    invoice_id             INTEGER NOT NULL,       -- degenerate dimension
    date_key               INTEGER NOT NULL,
    customer_key           INTEGER NOT NULL,
    track_key              INTEGER NOT NULL,
    billing_location_key   INTEGER NOT NULL,
    quantity               INTEGER NOT NULL CHECK (quantity > 0),
    unit_price             NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0),
    sales_amount           NUMERIC(12,2) NOT NULL CHECK (sales_amount >= 0),

    CONSTRAINT fk_fact_sales_date
        FOREIGN KEY (date_key) REFERENCES dim_date (date_key),
    CONSTRAINT fk_fact_sales_customer
        FOREIGN KEY (customer_key) REFERENCES dim_customer (customer_key),
    CONSTRAINT fk_fact_sales_track
        FOREIGN KEY (track_key) REFERENCES dim_track (track_key),
    CONSTRAINT fk_fact_sales_location
        FOREIGN KEY (billing_location_key)
        REFERENCES dim_billing_location (billing_location_key)
);

CREATE INDEX ix_fact_sales_date ON fact_sales (date_key);
CREATE INDEX ix_fact_sales_customer ON fact_sales (customer_key);
CREATE INDEX ix_fact_sales_track ON fact_sales (track_key);
CREATE INDEX ix_fact_sales_location ON fact_sales (billing_location_key);
CREATE INDEX ix_fact_sales_invoice ON fact_sales (invoice_id);

-- ETL mapping from the source Chinook database:
-- fact grain: InvoiceLine.InvoiceLineId (one purchased track per row)
-- date: Invoice.InvoiceDate -> dim_date
-- customer: Invoice.CustomerId -> dim_customer
-- track: InvoiceLine.TrackId -> dim_track
-- billing location: Invoice.Billing* -> dim_billing_location
-- measures: InvoiceLine.Quantity, InvoiceLine.UnitPrice,
--           sales_amount = Quantity * UnitPrice
--
-- dim_track is deliberately denormalized: Track + Album + Artist + Genre + MediaType
-- are flattened into one dimension to produce a STAR schema.
-- Customer profile country and invoice billing country are kept separately.
